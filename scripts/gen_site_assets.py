#!/usr/bin/env python3
"""Cut the landing page's images out of real captures of the desktop app.

Inputs (made by scripts/site_shots.mjs, 2x device pixels):
  servers.png                 the whole Servers tab, 1040x1800
  card-*.png, tunnel-*.png    single cards in different states
Outputs go to site/assets/img/. Requires Pillow.

It also writes site/data.js from the output of scripts/site_capture_cli.sh, so the terminals on the page show
what the CLI really printed.

Usage: scripts/gen_site_assets.py [ui-captures-dir [cli-captures-dir]]
"""
import pathlib
import shutil
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/pw/out")
CLI = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else "/tmp/cap/out")
OUT = ROOT / "site/assets/img"
OUT.mkdir(parents=True, exist_ok=True)

# name -> (left, top, right, bottom) in 2x pixels of servers.png. These are also the pieces' home
# positions in the exploded view in site/main.js, so change them together.
PIECES = {
    "p-card": (44, 1248, 996, 1620),  # the crashed card
    "p-badge": (812, 1258, 988, 1310),  # its CRASHED badge
    "p-url": (60, 616, 546, 686),  # http://shop.localhost:8080
    "p-run": (810, 436, 986, 492),  # the RUNNING light on the first card
    "p-daemon": (520, 30, 812, 98),  # DAEMON ACTIVE
    "p-count": (32, 302, 1008, 396),  # 2 RUNNING 1 CRASHED 1 IDLE
    "p-nav": (4, 1652, 1036, 1792),  # bottom navigation
    "p-btns": (62, 696, 372, 776),  # stop, restart, logs, settings
}

shot = Image.open(SRC / "servers.png").convert("RGBA")
shot.save(OUT / "app.png", optimize=True)
for name, box in PIECES.items():
    shot.crop(box).save(OUT / f"{name}.png", optimize=True)

for name in ["card-running", "card-crashed", "card-starting", "tunnel-connected", "tunnel-reconnecting"]:
    shutil.copy(SRC / f"{name}.png", OUT / f"{name}.png")

# the gargoyle, cut from the pixel-art sheet that also holds the wordmark
sheet = Image.open(ROOT / "design/Transparent Pixel Gargoyle Prot Logo.png").convert("RGBA")
garg = sheet.crop((846, 235, 1285, 720))
garg = garg.crop(garg.getchannel("A").getbbox())
# pixel art with a hard outline: a 160-colour palette keeps it intact at a third of the size
garg.quantize(160, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(OUT / "gargoyle.png", optimize=True)

icon = Image.open(ROOT / "design/icon.png").convert("RGBA")
icon.resize((64, 78), Image.LANCZOS).save(OUT / "favicon.png", optimize=True)
print("wrote", len(list(OUT.glob("*.png"))), "images to", OUT)

# real CLI output for the terminals on the page
import json

data = {p.stem: p.read_text().rstrip("\n") for p in sorted(CLI.glob("*.txt"))}
(ROOT / "site/data.js").write_text(
    "// Generated by scripts/gen_site_assets.py from real CLI output. Do not edit.\n"
    "window.PROT_OUT = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n"
)
print("wrote site/data.js with", len(data), "transcripts")
